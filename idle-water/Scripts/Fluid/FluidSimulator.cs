	// ============================================================
	// Physics
	// ============================================================

	public override void _PhysicsProcess(
		double delta)
	{
		Stopwatch physicsTimer =
			Stopwatch.StartNew();

		float dt =
			(float)delta;

		lastPhysicsDelta =
			dt;

		// --------------------------------------------------------
		// Reset per-frame energy counters
		// --------------------------------------------------------

		energyGeneratedThisFrame =
			0.0;

		if (
			wheelEnergyGeneratedThisFrame.Length !=
			wheelStates.Count)
		{
			wheelEnergyGeneratedThisFrame =
				new double[
					wheelStates.Count
				];
		}

		for (
			int i = 0;
			i < wheelEnergyGeneratedThisFrame.Length;
			i++)
		{
			wheelEnergyGeneratedThisFrame[i] =
				0.0;
		}

		// --------------------------------------------------------
		// Rain
		// --------------------------------------------------------

		Stopwatch spawnTimer =
			Stopwatch.StartNew();

		SpawnRainParticle(
			dt
		);

		UpdateRainHud();

		spawnTimer.Stop();

		fullSpawnTime +=
			spawnTimer.Elapsed.TotalMilliseconds;

		// --------------------------------------------------------
		// Additional wheel physics
		// --------------------------------------------------------

		StepAdditionalWheels(
			dt
		);

		// --------------------------------------------------------
		// PBF
		// --------------------------------------------------------

		Stopwatch pbfTimer =
			Stopwatch.StartNew();

		if (
			particles.Count > 0)
		{
			solver.Solve(
				particles,
				dt
			);
		}
		else
		{
			if (
				wheelStates.Count > 0)
			{
				wheelStates[0].Step(
					dt
				);
			}
		}

		pbfTimer.Stop();

		fullPbfTime +=
			pbfTimer.Elapsed.TotalMilliseconds;

		// --------------------------------------------------------
		// Energy + current indicator
		// --------------------------------------------------------

		bool currentGenerated =
			UpdateEnergyFromWheelRotation();

		UpdateCurrentIndicator(
			currentGenerated
		);

		// --------------------------------------------------------
		// Despawn particles
		// --------------------------------------------------------
		//
		// IMPORTANT:
		//
		// Particles leaving the simulation are permanently removed.
		// They are NOT recycled back to the rain spawn position.
		//
		// This must happen BEFORE the statistics graph is updated
		// so ActiveParticleCount represents the actual current
		// number of particles in the simulation.
		// --------------------------------------------------------

		RemoveParticlesAtOuterEdges();

		// --------------------------------------------------------
		// Update statistics graph
		// --------------------------------------------------------

		UpdateStatisticsHud(
			dt
		);

		// --------------------------------------------------------
		// Wheel visuals
		// --------------------------------------------------------

		UpdateWheelVisuals();

		// --------------------------------------------------------
		// Density
		// --------------------------------------------------------

		Stopwatch densityTimer =
			Stopwatch.StartNew();

		BuildDensityField();

		densityTimer.Stop();

		fullDensityTime +=
			densityTimer.Elapsed.TotalMilliseconds;

		// --------------------------------------------------------
		// Renderer
		// --------------------------------------------------------

		Stopwatch rendererTimer =
			Stopwatch.StartNew();

		renderer.Update(
			particles,
			densityField
		);

		rendererTimer.Stop();

		fullRendererTime +=
			rendererTimer.Elapsed.TotalMilliseconds;

		fullRendererBuildPixelsTime +=
			renderer.LastBuildPixelsMs;

		fullRendererSurfaceGlowTime +=
			renderer.LastSurfaceGlowMs;

		fullRendererFillBytesTime +=
			renderer.LastFillBytesMs;

		fullRendererTextureUploadTime +=
			renderer.LastTextureUploadMs;

		// --------------------------------------------------------
		// Profiler
		// --------------------------------------------------------

		physicsTimer.Stop();

		fullPhysicsTime +=
			physicsTimer.Elapsed.TotalMilliseconds;

		fullProfilerFrames++;

		if (
			fullProfilerFrames >=
			FullProfilerInterval)
		{
			PrintFullProfiler();

			ResetFullProfiler();
		}
	}

