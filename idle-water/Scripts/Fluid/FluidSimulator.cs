	// ============================================================
	// Find node by name
	// ============================================================

	private static T FindNodeByName<T>(
		Node node,
		string nodeName)
		where T : Node
	{
		if (
			node is T typedNode &&
			typedNode.Name == nodeName)
		{
			return typedNode;
		}

		foreach (
			Node child in
			node.GetChildren())
		{
			T result =
				FindNodeByName<T>(
					child,
					nodeName
				);

			if (
				result != null)
			{
				return result;
			}
		}

		return null;
	}

	// ============================================================
	// Find node by type
	// ============================================================

	private static T FindNodeOfType<T>(
		Node node)
		where T : Node
	{
		if (
			node is T typedNode)
		{
			return typedNode;
		}

		foreach (
			Node child in
			node.GetChildren())
		{
			T result =
				FindNodeOfType<T>(
					child
				);

			if (
				result != null)
			{
				return result;
			}
		}

		return null;
	}

