	private void InitializeDynamicRain()
	{
		SelectNewRainPhase();
	}

	private void SelectNewRainPhase()
	{
		int stepCount =
			(RainMaximumPercent - RainMinimumPercent) /
			RainPercentStep + 1;

		int randomStep =
			rainRandom.RandiRange(0, stepCount - 1);

		currentRainPercent =
			RainMinimumPercent +
			randomStep * RainPercentStep;

		rainPhaseTimer =
			rainRandom.RandfRange(
				RainMinimumDuration,
				RainMaximumDuration
			);

		GD.Print(
			"RAIN CHANGE -> " +
			currentRainPercent +
			"% for " +
			rainPhaseTimer.ToString("F1") +
			"s"
		);
	}

	private void UpdateDynamicRain(float dt)
	{
		rainPhaseTimer -= dt;

		if (rainPhaseTimer <= 0.0f)
		{
			SelectNewRainPhase();
		}
	}

	private void SpawnRainParticle(
		float dt)
	{
		UpdateDynamicRain(dt);

		// RainAmount = 100.0f is 50% rain.
		// Therefore: percentage / 50 gives the multiplier.
		float currentRainAmount =
			RainAmount *
			(currentRainPercent / 50.0f);

		if (
			particles.Count >=
			particles.Capacity)
		{
			return;
		}

		rainSpawnAccumulator +=
			currentRainAmount *
			dt;

		int spawnCount =
			(int)rainSpawnAccumulator;

		if (
			spawnCount <= 0)
		{
			return;
		}

		rainSpawnAccumulator -=
			spawnCount;

		for (
			int i = 0;
			i < spawnCount;
			i++)
		{
			if (
				particles.Count >=
				particles.Capacity)
			{
				break;
			}

			float x =
				rainRandom.RandfRange(
					WorldMinX,
					WorldMaxX
				);

			particles.AddParticle(
				x,
				RainSpawnY,
				RainVelocityX,
				RainVelocityY
			);

			totalRainSpawns++;
		}
	}

	// ============================================================
	// Despawn particles at outer edges
	// ============================================================
	//
	// Particles are permanently removed from the active set.
	//
	// IMPORTANT:
	//
	// ParticleData.RemoveParticle(index) moves the last active
	// particle into the removed slot and decreases Count.
	//
	// Therefore, after removing index i, we MUST NOT increment i.
	// The new particle occupying index i has not been checked yet.
	// ============================================================

	private void RemoveParticlesAtOuterEdges()
	{
		int i = 0;

		while (
			i < particles.Count)
		{
			float x =
				particles.PosX[i];

			float y =
				particles.PosY[i];

			bool outside =
				x <= DespawnLeftX ||
				x >= DespawnRightX ||
				y >= DespawnBottomY;

			if (
				outside)
			{
				particles.RemoveParticle(
					i
				);

				// Do NOT increment i.
				//
				// RemoveParticle() moved the previous last
				// active particle into this slot.
				continue;
			}

			i++;
		}
	}

	// ============================================================
	// Density field
	// ============================================================

	private void BuildDensityField()
	{
		densityField.Clear();

		for (
			int i = 0;
			i < particles.Count;
			i++)
		{
			densityField.AddParticle(
				particles.PosX[i],
				particles.PosY[i]
			);
		}
	}

