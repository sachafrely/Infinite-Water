			}
		}

		return null;
	}

	// ============================================================
	// Create wheels from marker tiles
	// ============================================================

	private void CreateWaterWheelsFromEnvironment()
	{
		TileMapLayer environment =
			FindEnvironment();

		if (
			environment == null)
		{
			GD.PushWarning(
				"FluidSimulator: Environment TileMapLayer " +
				"could not be found. No wheels created."
			);

			return;
		}

		GameViewMapping mapping =
			CreateGameViewMapping();

		if (
			!mapping.IsValid)
		{
			GD.PushWarning(
				"FluidSimulator: Could not establish " +
				"viewport mapping. No wheels created."
			);

			return;
		}

		IEnumerable<Vector2I> usedCells =
			environment.GetUsedCells();

		foreach (
			Vector2I cell in
			usedCells)
		{
			if (
				wheelStates.Count >=
				MaxWheelCount)
			{
				break;
			}

			int sourceId =
				environment.GetCellSourceId(
					cell
				);

			if (
				sourceId < 0)
			{
				continue;
			}

			Vector2I atlasCoords =
				environment.GetCellAtlasCoords(
					cell
				);

			if (
				atlasCoords.X !=
				WheelTileAtlasX ||
				atlasCoords.Y !=
				WheelTileAtlasY)
			{
				continue;
			}

			Vector2 tileCenterLocal =
				environment.MapToLocal(
					cell
				);

			Vector2 tileCenterGlobal =
				environment.ToGlobal(
					tileCenterLocal
				);

			Vector2 simulationPosition =
				mapping.ToSimulationSpace(
					tileCenterGlobal
				);

			CreateWaterWheel(
				simulationPosition
			);

			GD.Print(
				"Water wheel placed on Environment tile " +
				cell +
				" atlas " +
				atlasCoords +
				" -> simulation " +
				simulationPosition
			);
		}

		GD.Print(
			"Water wheels created from marker tiles: " +
			wheelStates.Count +
			"/" +
			MaxWheelCount
		);
	}

	// ============================================================
	// Viewport mapping
	// ============================================================

	private struct GameViewMapping
	{
		public SubViewportContainer GameView;
		public SubViewport SimulationViewport;
		public Camera2D Camera;

		public bool IsValid =>
			GameView != null &&
			SimulationViewport != null &&
			Camera != null;

		public Vector2 ToSimulationSpace(
			Vector2 globalPosition)
		{
			Vector2 viewportPoint =
				globalPosition -
				GameView.GlobalPosition;

			Vector2 viewportSize =
				new Vector2(
					SimulationViewport.Size.X,
					SimulationViewport.Size.Y
				);

			Vector2 screenCenter =
				viewportSize *
				0.5f;

			Vector2 cameraCenter =
				Camera.GetScreenCenterPosition();

			return
				cameraCenter +
				(
					viewportPoint -
					screenCenter
				);
		}
	}

	private GameViewMapping CreateGameViewMapping()
	{
		GameViewMapping mapping =
			new GameViewMapping();

		mapping.GameView =
			GetNodeOrNull<SubViewportContainer>(
				"../GameView"
			);

		if (
			mapping.GameView == null)
		{
			mapping.GameView =
				FindNodeOfType<SubViewportContainer>(
					GetTree().Root
				);
		}

		if (
			mapping.GameView != null)
		{
			mapping.SimulationViewport =
				mapping.GameView.GetNodeOrNull<SubViewport>(
					"SimulationViewport"
				);

			if (
				mapping.SimulationViewport == null)
			{
				foreach (
					Node child in
					mapping.GameView.GetChildren())
				{
					if (
						child is SubViewport)
					{
						mapping.SimulationViewport =
							(SubViewport)child;

						break;
					}
				}
			}
		}

		if (
			mapping.SimulationViewport != null)
		{
			mapping.Camera =
				mapping.SimulationViewport.GetNodeOrNull<Camera2D>(
					"Camera2D"
				);

			if (
				mapping.Camera == null)
			{
				mapping.Camera =
					FindNodeOfType<Camera2D>(
						mapping.SimulationViewport
					);
			}
		}

		return mapping;
	}

	// ============================================================
	// Create one wheel
	// ============================================================

	private void CreateWaterWheel(
		Vector2 center)
	{
		FluidWheelState wheelState;

		if (
			wheelStates.Count == 0)
		{
			wheelState =
				solver.CreateWheel(
					center
				);
		}
		else
		{
			wheelState =
				new FluidWheelState(
					center
				);
		}

		wheelStates.Add(
			wheelState
		);

		for (
			int i = 0;
			i < WheelBladeCount;
			i++)
		{
			float angle =
				Mathf.Tau *
				i /
				WheelBladeCount;

			Vector2 direction =
				new Vector2(
					Mathf.Cos(angle),
					Mathf.Sin(angle)
				);

			Vector2 tangent =
				new Vector2(
					-direction.Y,
					direction.X
				);

			Vector2 innerCenter =
				direction *
				WheelInnerRadius;

			Vector2 outerCenter =
				direction *
				WheelOuterRadius;

			Vector2[] blade =
			{
				innerCenter +
				tangent *
				WheelBladeWidth,

				outerCenter +
				tangent *
				WheelBladeWidth,

				outerCenter -
				tangent *
				WheelBladeWidth,

				innerCenter -
				tangent *
				WheelBladeWidth
			};

			FluidPolygonCollider collider =
				new FluidPolygonCollider(
					blade
				);

			collider.ConfigureAsWheel(
				wheelState
			);

			solver.AddPolygonCollider(
				collider
			);
		}

		const int hubSegments = 16;

		Vector2[] hub =
			new Vector2[
				hubSegments
			];

		for (
			int i = 0;
			i < hubSegments;
			i++)
		{
			float angle =
				Mathf.Tau *
				i /
				hubSegments;

			hub[i] =
				new Vector2(
					Mathf.Cos(angle),
					Mathf.Sin(angle)
				) *
				WheelInnerRadius;
		}

		FluidPolygonCollider hubCollider =
			new FluidPolygonCollider(
				hub
			);

		solver.AddPolygonCollider(
			hubCollider
		);

		WaterWheelVisual visual =
			new WaterWheelVisual();

		visual.Position =
			center;

		visual.OuterRadius =
			WheelOuterRadius;

		visual.InnerRadius =
			WheelInnerRadius;

		visual.BladeCount =
			WheelBladeCount;

		visual.BladeWidth =
			WheelBladeWidth;

		AddChild(
			visual
		);

		visual.SetWheelAngle(
			wheelState.Angle
		);

		wheelVisuals.Add(
			visual
		);
	}

